// Character lookup table: maps ASCII to font index
static int char_to_idx(char c) {
    switch(c) {
        case ' ': return 0;
        case '.': return 1;
        case 'P': return 2;
        case 'e': return 3;
        case 'l': return 4;
        case 't': return 5;
        case 'i': return 6;
        case 'r': return 7;
        case 'a': return 8;
        case 'o': return 9;
        case 'd': return 10;
        case 'n': return 11;
        case 'g': return 12;
        case 'L': return 13;
        case 'B': return 14;
        case 'V': return 15;
        case '2': return 16;
        default:  return 0;
    }
}

// Draw a single character at pixel position (x, y) with scale factor
static void draw_char(char c, int x, int y, int scale, uint16_t fg_color, uint16_t bg_color)
{
    int idx = char_to_idx(c);
    const uint8_t *glyph = font_8x16[idx];

    for (int row = 0; row < 16; row++) {
        for (int col = 0; col < 8; col++) {
            uint16_t color = (glyph[row] & (0x80 >> col)) ? fg_color : bg_color;
            if (scale == 1) {
                hx8357d_fill_rect(x + col, y + row, 1, 1, color);
            } else {
                hx8357d_fill_rect(x + col * scale, y + row * scale, scale, scale, color);
            }
        }
    }
}

// Draw a string at pixel position (x, y) with scale factor
static void draw_string(const char *str, int x, int y, int scale, uint16_t fg_color, uint16_t bg_color)
{
    int cx = x;
    for (int i = 0; str[i]; i++) {
        draw_char(str[i], cx, y, scale, fg_color, bg_color);
        cx += 8 * scale;
    }
}

void hx8357d_boot_splash(void)
{
    // Black background
    hx8357d_fill_screen(0x0000);

    // "PelletPirate" centered, scale 2 (16x32 per char)
    // 12 chars × 16px = 192px wide, centered in 320px → x=64
    uint16_t orange = HX8357D_RGB565(255, 107, 53);  // PelletPirate orange
    draw_string("PelletPirate", 64, 180, 2, orange, 0x0000);

    // "V2" below it
    draw_string("V2", 144, 220, 2, 0xFFFF, 0x0000);

    // "Loading..." at bottom
    draw_string("Loading...", 100, 300, 2, 0x8410, 0x0000);  // gray text
}
